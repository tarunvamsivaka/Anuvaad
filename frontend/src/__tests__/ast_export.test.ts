import { describe, it, expect } from 'vitest';

/**
 * Tests for ArtifactExportBar logic:
 *  - JSDoc injection (TypeScript)
 *  - PEP-257 docstring injection (Python)
 *  - GitHub PR Markdown generation
 *
 * We test the pure helper functions by importing the module and
 * exercising the exported logic via the smart-clipboard classifier
 * and the ast-line-mapper that ArtifactExportBar depends on.
 */

import { extractAstLineRanges, annotateBlocksWithLineRanges } from '../lib/ast-line-mapper';

// ── JSDoc Injection Helpers (extracted from ArtifactExportBar logic) ──────────

function injectJsDoc(lines: string[], lineIndex: number, docstring: string): void {
  const indent = lines[lineIndex]?.match(/^(\s*)/)?.[1] ?? '';
  const docLines = [
    `${indent}/**`,
    ...docstring.split('\n').map((l) => `${indent} * ${l.trim()}`),
    `${indent} */`,
  ];
  lines.splice(lineIndex, 0, ...docLines);
}

function injectPythonDocstring(lines: string[], lineIndex: number, docstring: string): void {
  const indent = (lines[lineIndex]?.match(/^(\s*)/)?.[1] ?? '') + '    ';
  const short = docstring.split('\n')[0].trim();
  lines.splice(lineIndex + 1, 0, `${indent}"""${short}"""`);
}

function generatePRMarkdown(blocks: Array<{ code_snippet?: string; english_translation?: string; startLine?: number; endLine?: number }>, language: string): string {
  const blockSection = blocks
    .map((b, i) => {
      const lineInfo = b.startLine && b.endLine ? ` (Lines ${b.startLine}–${b.endLine})` : '';
      return [
        `### Block ${i + 1}${lineInfo}`,
        '',
        '```',
        (b.code_snippet || '').trim(),
        '```',
        '',
        b.english_translation || '',
      ].join('\n');
    })
    .join('\n\n');

  return [
    '## Summary',
    '',
    `This PR contains ${blocks.length} logical block${blocks.length > 1 ? 's' : ''} of changes across ${language} code.`,
    '',
    '## Block-by-Block Changes',
    '',
    blockSection,
    '',
    '## Complexity & Edge Cases',
    '',
    `- **Total blocks:** ${blocks.length}`,
    `- **Language:** ${language}`,
    '',
    '_Generated by [Anuvaad](https://getanuvaad.vercel.app) — AI Code Translation Workspace_',
  ].join('\n');
}

// ── Tests ─────────────────────────────────────────────────────────────────────

describe('ArtifactExportBar — Docstring Injection', () => {
  it('injects JSDoc comments above TypeScript function declarations', () => {
    const code = [
      'export function add(a: number, b: number): number {',
      '  return a + b;',
      '}',
    ];

    injectJsDoc(code, 0, 'Adds two numbers and returns their sum.');

    expect(code[0]).toBe('/**');
    expect(code[1]).toContain('Adds two numbers');
    expect(code[2]).toBe(' */');
    expect(code[3]).toContain('export function add');
  });

  it('injects PEP-257 docstrings after Python function definitions', () => {
    const code = [
      'def calculate(x, y):',
      '    return x * y',
    ];

    injectPythonDocstring(code, 0, 'Multiplies two numbers.');

    expect(code[0]).toBe('def calculate(x, y):');
    expect(code[1]).toContain('"""Multiplies two numbers."""');
    expect(code[2]).toBe('    return x * y');
  });

  it('injects multiple JSDoc blocks with correct line offsets', () => {
    const code = [
      'function greet(name: string): string {',
      '  return `Hello, ${name}!`;',
      '}',
      '',
      'function farewell(name: string): string {',
      '  return `Goodbye, ${name}!`;',
      '}',
    ];

    // Inject at line 0 first
    injectJsDoc(code, 0, 'Greets the user.');
    // After injection, "farewell" has shifted down by 3 lines (/** * */ = 3 lines)
    const farewellIdx = code.findIndex((l) => l.includes('function farewell'));
    injectJsDoc(code, farewellIdx, 'Bids farewell to the user.');

    expect(code.join('\n')).toContain('/**');
    expect(code.join('\n')).toContain('Greets the user.');
    expect(code.join('\n')).toContain('Bids farewell');
    expect(code.join('\n')).toContain('function greet');
    expect(code.join('\n')).toContain('function farewell');
  });
});

describe('ArtifactExportBar — GitHub PR Markdown', () => {
  it('generates valid PR markdown with all required sections', () => {
    const blocks = [
      {
        code_snippet: 'function add(a, b) { return a + b; }',
        english_translation: 'Implements an addition function that returns the sum of two numbers.',
        startLine: 1,
        endLine: 1,
      },
      {
        code_snippet: 'function multiply(a, b) { return a * b; }',
        english_translation: 'Implements a multiplication function.',
        startLine: 3,
        endLine: 3,
      },
    ];

    const md = generatePRMarkdown(blocks, 'javascript');

    expect(md).toContain('## Summary');
    expect(md).toContain('## Block-by-Block Changes');
    expect(md).toContain('## Complexity & Edge Cases');
    expect(md).toContain('Lines 1–1');
    expect(md).toContain('Lines 3–3');
    expect(md).toContain('Block 1');
    expect(md).toContain('Block 2');
    expect(md).toContain('javascript');
    expect(md).toContain('Anuvaad');
    expect(md).toContain('**Total blocks:** 2');
  });

  it('handles blocks without line ranges gracefully', () => {
    const blocks = [
      {
        code_snippet: 'const x = 42;',
        english_translation: 'Declares a constant variable x with value 42.',
      },
    ];

    const md = generatePRMarkdown(blocks, 'typescript');
    expect(md).toContain('## Summary');
    expect(md).toContain('Block 1');
    expect(md).not.toContain('Lines –'); // No line info if no startLine/endLine
  });
});

describe('ArtifactExportBar — AST Audit Integration', () => {
  it('extractAstLineRanges correctly identifies TypeScript symbols', () => {
    const tsCode = [
      'export function multiply(a: number, b: number): number {',
      '  return a * b;',
      '}',
      '',
      'export class Calculator {',
      '  add(x: number, y: number) { return x + y; }',
      '}',
    ].join('\n');

    const ranges = extractAstLineRanges(tsCode, 'typescript');
    expect(ranges.length).toBeGreaterThanOrEqual(2);
    const fnRange = ranges.find((r) => r.name === 'multiply');
    expect(fnRange).toBeDefined();
    expect(fnRange?.type).toBe('export');
  });

  it('annotateBlocksWithLineRanges correctly wires line ranges to blocks', () => {
    const code = [
      'def greet(name):',
      '    return f"Hello, {name}!"',
    ].join('\n');

    const blocks = [
      { id: 'b1', code_snippet: 'def greet(name):', english_translation: 'Greets by name.' },
    ];

    const annotated = annotateBlocksWithLineRanges(code, blocks, 'python');
    expect(annotated[0].startLine).toBeDefined();
    expect(annotated[0].endLine).toBeDefined();
    expect(annotated[0].startLine).toBeGreaterThanOrEqual(1);
  });
});
